def test_owner_can_edit_and_other_user_cannot(cleanup):
    owner = User.objects.create_user('test_owner', password=PASSWORD)
    other = User.objects.create_user('test_other', password=PASSWORD)
    feed = _make_feed(owner=owner)

    client = Client()
    client.force_login(owner)
    response = client.get('/en/setup/%s' % feed.id)
    assert response.status_code == 200

    data = {'uri': TEST_URI + 'updated', 'feed_xpath': '//section'}
    for field in _fields():
        data['xpath_%s' % field.name] = '//updated-%s' % field.name
    response = client.post('/en/setup/%s' % feed.id, data)
    assert response.status_code == 302

    feed.refresh_from_db()
    assert feed.uri == TEST_URI + 'updated'
    assert feed.xpath == '//section'
    assert feed.edited is True
    assert FeedField.objects.filter(
        feed=feed, field__name='title', xpath='//updated-title').exists()

    other_client = Client()
    other_client.force_login(other)
    assert other_client.get('/en/setup/%s' % feed.id).status_code == 403
    assert other_client.post('/en/myfeeds/delete/%s' % feed.id).status_code == 403


