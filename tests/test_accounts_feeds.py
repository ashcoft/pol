def _fields():
    fields = list(Field.objects.order_by('id'))
    if not fields:
        pytest.skip('Field fixture is not loaded')
    return fields


def _make_feed(owner=None, session_key=''):
    feed = Feed.objects.create(
        uri=TEST_URI + 'page', xpath='//article',
        owner=owner, session_key=session_key)
    for field in _fields():
        FeedField.objects.create(
            feed=feed, field=field, xpath='//%s' % field.name)
    return feed


