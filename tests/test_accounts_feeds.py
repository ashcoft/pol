def _edit_data(uri=None, feed_xpath='//article', **overrides):
    data = {'uri': uri or (TEST_URI + 'page'), 'feed_xpath': feed_xpath}
    for field in _fields():
        data['xpath_%s' % field.name] = overrides.get(
            field.name, '//%s' % field.name)
    return data


