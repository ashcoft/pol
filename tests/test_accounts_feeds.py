"""Account and feed-management tests.

These need a migrated database. CI's plain pytest job has no PostgreSQL
service, so the module skips there; it runs wherever the configured database
has been prepared with ``manage.py migrate``.
"""

import json
import os

import pytest

django = pytest.importorskip('django')

os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'frontend.frontend.settings')
try:
    django.setup()
except Exception as exc:  # settings.py is generated by CI and git-ignored
    pytest.skip('Django settings unavailable: %s' % exc, allow_module_level=True)

from django.contrib.auth.models import User  # noqa: E402
from django.db import connection  # noqa: E402
from django.test import Client, override_settings  # noqa: E402

from frontend.frontend.models import Feed, Field, FeedField  # noqa: E402


def _db_ready():
    try:
        with connection.cursor() as cur:
            cur.execute('SELECT 1 FROM frontend_field LIMIT 1')
        return True
    except Exception:
        try:
            connection.close()
        except Exception:
            pass
        return False


pytestmark = pytest.mark.skipif(
    not _db_ready(), reason='Django database is not migrated')

USERNAMES = ('test_signup_user', 'test_owner', 'test_other')
TEST_URI = 'https://example.test/'
PASSWORD = 'a-very-strong-pass-123'


@pytest.fixture(autouse=True)
def _settings():
    with override_settings(
            ROOT_URLCONF='frontend.frontend.urls',
            ALLOWED_HOSTS=['testserver']):
        yield


@pytest.fixture
def cleanup():
    def remove():
        Feed.objects.filter(uri__startswith=TEST_URI).delete()
        User.objects.filter(username__in=USERNAMES).delete()

    remove()
    yield
    remove()


def _fields():
    fields = list(Field.objects.order_by('id'))
    if not fields:
        pytest.skip('Field fixture is not loaded')
    return fields


def _make_feed(owner=None, session_key=''):
    feed = Feed.objects.create(
        uri=TEST_URI + 'page', xpath='//article',
        owner=owner, session_key=session_key)
    for field in _fields():
        FeedField.objects.create(
            feed=feed, field=field, xpath='//%s' % field.name)
    return feed


def test_signup_logs_in_and_lists_feeds(cleanup):
    client = Client()
    response = client.post('/en/accounts/signup/', {
        'username': 'test_signup_user',
        'password1': PASSWORD,
        'password2': PASSWORD,
    })
    assert response.status_code == 302
    assert response['Location'] == '/en/myfeeds'
    assert User.objects.filter(username='test_signup_user').exists()

    response = client.get('/en/myfeeds')
    assert response.status_code == 200
    assert b'My feeds' in response.content


def test_owner_can_edit_and_other_user_cannot(cleanup):
    owner = User.objects.create_user('test_owner', password=PASSWORD)
    other = User.objects.create_user('test_other', password=PASSWORD)
    feed = _make_feed(owner=owner)

    client = Client()
    client.force_login(owner)
    response = client.get('/en/setup/%s' % feed.id)
    assert response.status_code == 200

    data = {'uri': TEST_URI + 'updated', 'feed_xpath': '//section'}
    for field in _fields():
        data['xpath_%s' % field.name] = '//updated-%s' % field.name
    response = client.post('/en/setup/%s' % feed.id, data)
    assert response.status_code == 302

    feed.refresh_from_db()
    assert feed.uri == TEST_URI + 'updated'
    assert feed.xpath == '//section'
    assert feed.edited is True
    assert FeedField.objects.filter(
        feed=feed, field__name='title', xpath='//updated-title').exists()

    other_client = Client()
    other_client.force_login(other)
    assert other_client.get('/en/setup/%s' % feed.id).status_code == 403
    assert other_client.post('/en/myfeeds/delete/%s' % feed.id).status_code == 403


def test_anonymous_session_feed_is_listed_and_editable(cleanup):
    client = Client()
    session = client.session
    session['seed'] = '1'
    session.save()
    feed = _make_feed(session_key=session.session_key)

    response = client.get('/en/myfeeds')
    assert response.status_code == 200
    assert (TEST_URI + 'page').encode() in response.content

    assert client.get('/en/setup/%s' % feed.id).status_code == 200


def test_anonymous_creation_stores_session_key(cleanup):
    html = [
        'html', {'tag-id': 1}, [
            ['body', {'tag-id': 2}, [
                ['article', {'tag-id': 3}, [
                    ['h1', {'tag-id': 4}, []],
                    ['p', {'tag-id': 5}, []],
                ]],
            ]],
        ],
    ]
    client = Client()
    response = client.post(
        '/setup_create_feed',
        data=json.dumps({
            'html': html,
            'names': {'title': 4, 'description': 5},
            'url': TEST_URI + 'created',
        }),
        content_type='application/json')
    assert response.status_code == 200

    feed = Feed.objects.get(uri=TEST_URI + 'created')
    assert feed.owner_id is None
    assert feed.session_key
    assert feed.session_key == client.session.session_key
    assert FeedField.objects.filter(feed=feed).count() >= 2


def test_login_rejects_external_next_redirect(cleanup):
    User.objects.create_user('test_owner', password=PASSWORD)
    client = Client()
    response = client.post('/en/accounts/login/?next=https://evil.example/', {
        'username': 'test_owner',
        'password': PASSWORD,
        'next': 'https://evil.example/',
    })
    assert response.status_code == 302
    assert response['Location'] == '/en/myfeeds'
