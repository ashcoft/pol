"""Tests for the Django discovery proxy (real HTTP, no mocks)."""

import json
import os

import pytest

django = pytest.importorskip('django')

try:
    import MySQLdb  # noqa: F401
except ImportError:  # local runs without mysqlclient
    pymysql = pytest.importorskip('pymysql')
    pymysql.install_as_MySQLdb()

os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'frontend.frontend.settings')
try:
    django.setup()
except Exception as exc:  # settings.py is generated by CI and git-ignored
    pytest.skip('Django settings unavailable: %s' % exc, allow_module_level=True)

from django.test import Client, override_settings  # noqa: E402

from frontend.frontend import views  # noqa: E402

TEST_SETTINGS = dict(ROOT_URLCONF='frontend.frontend.urls', ALLOWED_HOSTS=['testserver'])


@override_settings(**TEST_SETTINGS)
def test_discover_requires_url():
    response = Client().get('/discover')
    assert response.status_code == 400


@override_settings(**TEST_SETTINGS)
def test_discover_rejects_invalid_url():
    response = Client().get('/discover', {'url': 'mailto:x@example.com'})
    assert response.status_code == 400


@override_settings(**TEST_SETTINGS)
def test_discover_proxies_to_the_downloader(http_server, monkeypatch):
    seen = {}

    def route(method, handler):
        seen['path'] = handler.path
        return 200, {'Content-Type': 'application/json'}, json.dumps({
            'feeds': [{'title': 'Example', 'url': 'https://example.com/feed',
                       'type': 'application/rss+xml'}],
        })

    http_server.routes['/discover'] = route
    monkeypatch.setattr(views, 'DOWNLOADER_BASE_URL', http_server.base_url)

    response = Client().get('/discover', {'url': 'example.com/blog'})
    assert response.status_code == 200
    payload = json.loads(response.content)
    assert payload['feeds'][0]['url'] == 'https://example.com/feed'
    assert 'url=https%3A%2F%2Fexample.com%2Fblog' in seen['path']


@override_settings(**TEST_SETTINGS)
def test_discover_reports_downloader_failure(http_server, monkeypatch):
    http_server.routes['/discover'] = (502, {'Content-Type': 'application/json'},
                                       '{"error": "upstream"}')
    monkeypatch.setattr(views, 'DOWNLOADER_BASE_URL', http_server.base_url)

    response = Client().get('/discover', {'url': 'https://example.com/'})
    assert response.status_code == 502
    assert json.loads(response.content)['error'] == 'upstream'
